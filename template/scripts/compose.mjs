/**
 * Manual compose (CC-026), the file steps of `hipster new` until the CLI exists
 * (application.yaml → cli.new.pipeline): copy the template, delete files owned
 * by unselected modules, strip `// @module <removed>` lines, rewrite the
 * registry and the manifest, rebuild .env.example. No install, no git.
 *
 *   node scripts/compose.mjs <out-dir> [module ...]   (dependsOn closure added)
 */
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { renderEnvExample } from "./env-example.mjs";
import { validateManifest } from "./modules-schema.mjs";
import { BASE, listFiles, ownerOf } from "./ownership.mjs";

const REGISTRY = "lib/modules/registry.ts";

/** The selection plus everything it depends on, in manifest order. */
export function closure(manifest, selected) {
  const keep = new Set();
  const visit = (id) => {
    if (keep.has(id)) return;
    const entry = manifest.modules.find((candidate) => candidate.id === id);
    if (!entry) throw new Error(`unknown module "${id}"`);
    keep.add(id);
    entry.dependsOn.forEach(visit);
  };
  selected.forEach(visit);
  return manifest.modules.map(({ id }) => id).filter((id) => keep.has(id));
}

const camel = (id) => `${id}Module`;

export function renderRegistry(ids) {
  return [
    "// generated by hipster-stack — do not edit by hand",
    'import type { ModuleDefinition } from "@/types/moduleTypes";',
    ...(ids.length > 0 ? [""] : []),
    ...ids.map(
      (id) => `import { ${camel(id)} } from "@/lib/modules/${id}.module";`,
    ),
    "",
    ids.length > 0
      ? `export const installedModules: readonly ModuleDefinition[] = [\n${ids.map((id) => `  ${camel(id)},`).join("\n")}\n];`
      : "export const installedModules: readonly ModuleDefinition[] = [];",
    "",
  ].join("\n");
}

/**
 * @returns {{ modules: string[], files: number, removed: number }}
 */
export function compose(root, outDir, selected) {
  const raw = JSON.parse(
    readFileSync(path.join(root, "hipster.modules.json"), "utf8"),
  );
  const result = validateManifest(raw);
  if (!result.ok) throw new Error("hipster.modules.json is invalid");
  const { manifest } = result;
  const ids = closure(manifest, selected);
  const removedIds = new Set(
    manifest.modules.map(({ id }) => id).filter((id) => !ids.includes(id)),
  );

  let files = 0;
  let removed = 0;
  for (const file of listFiles(root)) {
    const source = path.join(root, file);
    if (!existsSync(source)) continue;
    const { owner } = ownerOf(file, manifest);
    if (owner !== BASE && owner !== null && removedIds.has(owner)) {
      removed += 1;
      continue;
    }
    const target = path.join(outDir, file);
    mkdirSync(path.dirname(target), { recursive: true });
    if (file.endsWith(".prisma")) {
      const kept = readFileSync(source, "utf8")
        .split("\n")
        .filter((line) => {
          const tag = /\/\/ @module (\w+)\s*$/.exec(line);
          return !(tag && removedIds.has(tag[1]));
        })
        .join("\n");
      writeFileSync(target, kept);
    } else {
      cpSync(source, target);
    }
    files += 1;
  }

  writeFileSync(path.join(outDir, REGISTRY), renderRegistry(ids));
  const composed = {
    ...raw,
    modules: raw.modules.filter(({ id }) => ids.includes(id)),
    presets: {},
  };
  writeFileSync(
    path.join(outDir, "hipster.modules.json"),
    `${JSON.stringify(composed, null, 2)}\n`,
  );
  const composedManifest = validateManifest(composed);
  if (!composedManifest.ok) {
    throw new Error(
      `composed manifest is invalid: ${composedManifest.errors.join("; ")}`,
    );
  }
  writeFileSync(
    path.join(outDir, ".env.example"),
    renderEnvExample(composedManifest.manifest),
  );
  return { modules: ids, files, removed };
}

const isMain = process.argv[1] === fileURLToPath(import.meta.url);
if (isMain) {
  const [outDir, ...selected] = process.argv.slice(2);
  if (!outDir) {
    console.error("usage: node scripts/compose.mjs <out-dir> [module ...]");
    process.exit(1);
  }
  const root = fileURLToPath(new URL("..", import.meta.url));
  const { modules, files, removed } = compose(
    root,
    path.resolve(outDir),
    selected,
  );
  process.stdout.write(
    `composed base + [${modules.join(", ")}]: ${files} files, ${removed} module files left out\n`,
  );
}
