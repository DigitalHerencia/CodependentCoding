/**
 * Renders `.env.example` from the `env` entries in hipster.modules.json: base
 * first, then modules in manifest order. The CLI reruns it for generated apps.
 *
 *   node scripts/env-example.mjs          write .env.example
 *   node scripts/env-example.mjs --check  fail if .env.example is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { validateManifest } from "./modules-schema.mjs";

/** @param {{ base: { env: object[] }, modules: { id: string, label: string, env: object[] }[] }} manifest */
export function renderEnvExample(manifest) {
  const sections = [
    ["Base", manifest.base.env],
    ...manifest.modules.map((entry) => [
      `${entry.label} (${entry.id})`,
      entry.env,
    ]),
  ].filter(([, env]) => env.length > 0);

  const lines = [
    "# Generated by scripts/env-example.mjs from hipster.modules.json; do not edit.",
    "# Copy to .env.local. Blank values count as unset.",
  ];
  for (const [title, env] of sections) {
    lines.push("", `# ${title}`);
    for (const { name, required, description } of env) {
      const note = [required ? "required" : "optional", description]
        .filter(Boolean)
        .join(": ");
      lines.push(`# ${note}`, `${name}=""`);
    }
  }
  return `${lines.join("\n")}\n`;
}

const isMain = process.argv[1] === fileURLToPath(import.meta.url);
if (isMain) {
  const root = fileURLToPath(new URL("..", import.meta.url));
  const result = validateManifest(
    JSON.parse(readFileSync(`${root}/hipster.modules.json`, "utf8")),
  );
  if (!result.ok) {
    console.error("hipster.modules.json: invalid; run pnpm check:modules");
    process.exit(1);
  }
  const rendered = renderEnvExample(result.manifest);
  const target = `${root}/.env.example`;
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== rendered) {
      console.error(
        ".env.example is stale; run `node scripts/env-example.mjs`",
      );
      process.exit(1);
    }
    process.stdout.write(".env.example: up to date\n");
  } else {
    writeFileSync(target, rendered);
    process.stdout.write("wrote .env.example\n");
  }
}
