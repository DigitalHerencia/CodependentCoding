import re,glob,sys
from collections import Counter
os_dir=sys.argv[1]
import os; os.chdir(os_dir)
defs={}; titles={}
for f in sorted(glob.glob('[01]*.md')):
    t=open(f).read()
    titles[f]=(re.search(r'^title: (.*)$',t,re.M).group(1), re.search(r'^slug: (.*)$',t,re.M).group(1))
    body=[]
    for mm in re.finditer(r'> \*\*(CC-[A-Z0-9]+-\d+)\*\* · `([a-z]+)`[^·\n]*· ([^\n]+)\n> ([^\n]+)',t):
        body.append(mm.group(1))
        if mm.group(1) in defs: print('DUP',mm.group(1),f)
        defs.setdefault(mm.group(1),(f,mm.group(2),mm.group(3).strip(),mm.group(4).strip()))
    k=lambda i:(i.split('-')[1],int(i.split('-')[2]))
    if re.search(r'^rules: \[',t,re.M):
        t=re.sub(r'^rules: \[.*\]$','rules: ['+', '.join(sorted(set(body),key=k))+']',t,flags=re.M); open(f,'w').write(t)
def key(i): a,b,n=i.split('-'); return (b,int(n))
c=Counter(v[1] for v in defs.values())
rows=[f"| [`{r}`](/doctrine/{titles[defs[r][0]][1]}#{r.lower()}) | `{defs[r][1]}` | {defs[r][3].replace('|','\\|')} | {defs[r][2].replace('|','\\|')} | {titles[defs[r][0]][0]} |" for r in sorted(defs,key=key)]
open('90-appendix-a-rule-index.md','w').write(f"""---
title: Rule Index
slug: rules
order: 90
summary: Every CC rule with its tier, enforcement and chapter. Generated from the chapters; do not edit by hand.
---

# Rule Index

{len(defs)} rules: {c['now']} `now`, {c['users']} `users`, {c['scale']} `scale`. Each ID links to the paragraph that justifies it. This table is generated by `pnpm doctrine:index` from the rule blocks in the chapters; `pnpm doctrine:check` fails when it, `validation.yaml` and the lint plugin disagree.

| ID | Tier | Rule | Enforcement | Chapter |
| --- | --- | --- | --- | --- |
"""+"\n".join(rows)+"\n")
print(len(defs),dict(c))
