/**
 * Generates plugin/loaded-vibes/references/doctrine.md: the classifier from
 * Architecture.md §3.3 and the CC-* rule table from validation.yaml. Never edit
 * the output by hand; change the sources and rerun.
 *
 *   pnpm plugin:doctrine          write
 *   pnpm plugin:doctrine --check  exit 1 when the file is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { format, resolveConfig } from "prettier";
import { parse } from "yaml";

const root = fileURLToPath(new URL("..", import.meta.url));
const ARCHITECTURE = "context/docs/Architecture.md";
const VALIDATION = ".claude/contracts/validation.yaml";
const OUTPUT = "plugin/loaded-vibes/references/doctrine.md";

function classifier() {
  const text = readFileSync(`${root}${ARCHITECTURE}`, "utf8");
  const match =
    /^### 3\.3 Classifier[^\n]*\n[\s\S]*?```text\n([\s\S]*?)```/m.exec(text);
  if (!match) throw new Error(`${ARCHITECTURE}: no §3.3 classifier block`);
  return match[1].trimEnd();
}

const cell = (value) => String(value).replaceAll("|", "\\|");

function ruleTable() {
  const { rules } = parse(readFileSync(`${root}${VALIDATION}`, "utf8"));
  return [
    "| ID | Layer | Rule | Enforced by |",
    "| --- | --- | --- | --- |",
    ...rules.map(
      ({ id, layer, text, enforcement }) =>
        `| ${id} | ${layer} | ${cell(text)} | \`${cell(enforcement)}\` |`,
    ),
  ].join("\n");
}

/** Prettier-formatted, so `pnpm format:check` and `--check` agree. */
export async function renderDoctrine() {
  const output = `${root}${OUTPUT}`;
  const markdown = `<!-- Generated by scripts/plugin-doctrine.mjs from ${ARCHITECTURE} §3.3 and ${VALIDATION}. Do not edit. -->

# Codependent Coding doctrine (condensed)

Classify before creating a file. Lint findings print a CC-* ID: fix the cause, never disable the rule. Never report a check as passing unless you ran it.

## Classifier

Answer top to bottom; the first yes is the file's home. \`<d>\` is the domain (module id).

\`\`\`text
${classifier()}
\`\`\`

## Rules

${ruleTable()}
`;
  return format(markdown, {
    ...(await resolveConfig(output)),
    filepath: output,
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = `${root}${OUTPUT}`;
  const next = await renderDoctrine();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(output, "utf8");
    } catch {
      // missing counts as stale
    }
    if (current !== next) {
      console.error(`${OUTPUT} is stale. Run: pnpm plugin:doctrine`);
      process.exit(1);
    }
  } else {
    writeFileSync(output, next);
    console.log(`wrote ${OUTPUT}`);
  }
}
